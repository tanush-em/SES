#!/usr/bin/env python3
"""Copy kit skeleton/standards/product-cursor into ses_cli/data for wheel packaging."""

from __future__ import annotations

import shutil
import sys
from pathlib import Path


def main() -> int:
    cli_root = Path(__file__).resolve().parents[1]
    kit_root = cli_root.parents[1]
    data = cli_root / "src" / "ses_cli" / "data"

    mapping = {
        kit_root / "skeleton": data / "skeleton",
        kit_root / "standards": data / "standards",
        kit_root / "templates" / "product-cursor": data / "product-cursor",
    }
    for src, dest in mapping.items():
        if not src.is_dir():
            print(f"missing source: {src}", file=sys.stderr)
            return 1
        if dest.exists():
            shutil.rmtree(dest)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(
            src,
            dest,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"),
        )
        print(f"synced {src} -> {dest}")

    # Marker so package discovers data/
    (data / "README").write_text(
        "Vendored SES kit data. Regenerated by scripts/sync_package_data.py.\n",
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
